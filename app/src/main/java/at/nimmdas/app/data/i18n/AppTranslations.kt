    fun t(key: String, locale: String): String {
        val activeLocale = if (translations.containsKey(locale)) locale else "de"
        return translations[activeLocale]?.get(key) ?: translations["de"]?.get(key) ?: key
    }

    fun tFormat(key: String, locale: String, vararg args: Any): String {
        return try {
            String.format(t(key, locale), *args)
        } catch (_: Exception) {
            t(key, locale)
        }
    }
